-- Agrotechnica | MariaDB 10.x | utf8mb4
SET NAMES utf8mb4;

CREATE TABLE IF NOT EXISTS users (
  id INT UNSIGNED AUTO_INCREMENT PRIMARY KEY,
  email VARCHAR(190) NOT NULL UNIQUE,
  full_name VARCHAR(120),
  password_hash VARCHAR(100) NOT NULL,           -- bcrypt
  role ENUM('admin','editor') NOT NULL DEFAULT 'editor',
  failed_logins TINYINT UNSIGNED NOT NULL DEFAULT 0,
  locked_until DATETIME NULL,
  created_at DATETIME DEFAULT CURRENT_TIMESTAMP
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4;

CREATE TABLE IF NOT EXISTS media (
  id INT UNSIGNED AUTO_INCREMENT PRIMARY KEY,
  url VARCHAR(255) NOT NULL,                     -- ex: /uploads/2026/11/abc.webp
  alt_text VARCHAR(255),
  width INT, height INT, size_bytes INT,
  created_at DATETIME DEFAULT CURRENT_TIMESTAMP
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4;

CREATE TABLE IF NOT EXISTS site_settings (
  id TINYINT UNSIGNED PRIMARY KEY DEFAULT 1,
  company_name VARCHAR(120), tagline VARCHAR(190),
  whatsapp_number VARCHAR(20),                   -- 5561996275673
  phone VARCHAR(30), email VARCHAR(150),
  address VARCHAR(255), city VARCHAR(80), state CHAR(2), zip VARCHAR(12),
  maps_embed_url TEXT, maps_link VARCHAR(500),
  instagram_url VARCHAR(255), facebook_url VARCHAR(255),
  youtube_url VARCHAR(255), linkedin_url VARCHAR(255),
  opening_hours JSON,
  updated_at DATETIME DEFAULT CURRENT_TIMESTAMP ON UPDATE CURRENT_TIMESTAMP,
  CHECK (id = 1)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4;

CREATE TABLE IF NOT EXISTS whatsapp_messages (
  id INT UNSIGNED AUTO_INCREMENT PRIMARY KEY,
  route_pattern VARCHAR(120) NOT NULL UNIQUE,    -- '/', '/servicos/*'
  message VARCHAR(500) NOT NULL
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4;

CREATE TABLE IF NOT EXISTS page_sections (
  id INT UNSIGNED AUTO_INCREMENT PRIMARY KEY,
  page VARCHAR(40) NOT NULL, section_key VARCHAR(40) NOT NULL,
  eyebrow VARCHAR(120), title VARCHAR(255), subtitle TEXT, body MEDIUMTEXT,
  cta_label VARCHAR(80), cta_url VARCHAR(255),
  image_id INT UNSIGNED NULL,
  extra JSON,
  is_published TINYINT(1) NOT NULL DEFAULT 1,
  UNIQUE KEY uq_page_section (page, section_key),
  FOREIGN KEY (image_id) REFERENCES media(id) ON DELETE SET NULL
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4;

CREATE TABLE IF NOT EXISTS banners (
  id INT UNSIGNED AUTO_INCREMENT PRIMARY KEY,
  title VARCHAR(190), subtitle VARCHAR(255),
  cta_label VARCHAR(80), cta_url VARCHAR(255),
  image_id INT UNSIGNED NULL, mobile_image_id INT UNSIGNED NULL,
  position INT NOT NULL DEFAULT 0, is_published TINYINT(1) NOT NULL DEFAULT 1,
  FOREIGN KEY (image_id) REFERENCES media(id) ON DELETE SET NULL,
  FOREIGN KEY (mobile_image_id) REFERENCES media(id) ON DELETE SET NULL
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4;

CREATE TABLE IF NOT EXISTS services (
  id INT UNSIGNED AUTO_INCREMENT PRIMARY KEY,
  slug VARCHAR(120) NOT NULL UNIQUE,
  title VARCHAR(190) NOT NULL, short_description VARCHAR(300), body MEDIUMTEXT,
  icon VARCHAR(40), image_id INT UNSIGNED NULL,
  features JSON,
  position INT NOT NULL DEFAULT 0, is_published TINYINT(1) NOT NULL DEFAULT 1,
  seo_title VARCHAR(70), seo_description VARCHAR(170),
  FOREIGN KEY (image_id) REFERENCES media(id) ON DELETE SET NULL
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4;

CREATE TABLE IF NOT EXISTS brands (
  id INT UNSIGNED AUTO_INCREMENT PRIMARY KEY,
  name VARCHAR(80) NOT NULL, logo_id INT UNSIGNED NULL, position INT NOT NULL DEFAULT 0,
  FOREIGN KEY (logo_id) REFERENCES media(id) ON DELETE SET NULL
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4;

CREATE TABLE IF NOT EXISTS product_categories (
  id INT UNSIGNED AUTO_INCREMENT PRIMARY KEY,
  slug VARCHAR(80) NOT NULL UNIQUE, name VARCHAR(80) NOT NULL, position INT NOT NULL DEFAULT 0
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4;

CREATE TABLE IF NOT EXISTS products (          -- sem preço: sempre "Solicite orçamento"
  id INT UNSIGNED AUTO_INCREMENT PRIMARY KEY,
  slug VARCHAR(140) NOT NULL UNIQUE,
  name VARCHAR(190) NOT NULL, description TEXT,
  category_id INT UNSIGNED NULL, brand_id INT UNSIGNED NULL, image_id INT UNSIGNED NULL,
  in_stock TINYINT(1) NOT NULL DEFAULT 1,        -- "pronta entrega"
  is_featured TINYINT(1) NOT NULL DEFAULT 0,
  is_published TINYINT(1) NOT NULL DEFAULT 1,
  seo_title VARCHAR(70), seo_description VARCHAR(170),
  FOREIGN KEY (category_id) REFERENCES product_categories(id) ON DELETE SET NULL,
  FOREIGN KEY (brand_id) REFERENCES brands(id) ON DELETE SET NULL,
  FOREIGN KEY (image_id) REFERENCES media(id) ON DELETE SET NULL
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4;

CREATE TABLE IF NOT EXISTS portfolio_items (
  id INT UNSIGNED AUTO_INCREMENT PRIMARY KEY,
  slug VARCHAR(140) NOT NULL UNIQUE,
  title VARCHAR(190) NOT NULL, description TEXT, category VARCHAR(60),
  cover_id INT UNSIGNED NULL,
  is_published TINYINT(1) NOT NULL DEFAULT 1, position INT NOT NULL DEFAULT 0,
  FOREIGN KEY (cover_id) REFERENCES media(id) ON DELETE SET NULL
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4;

CREATE TABLE IF NOT EXISTS portfolio_images (
  id INT UNSIGNED AUTO_INCREMENT PRIMARY KEY,
  item_id INT UNSIGNED NOT NULL, media_id INT UNSIGNED NOT NULL,
  caption VARCHAR(255), position INT NOT NULL DEFAULT 0,
  FOREIGN KEY (item_id) REFERENCES portfolio_items(id) ON DELETE CASCADE,
  FOREIGN KEY (media_id) REFERENCES media(id) ON DELETE CASCADE
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4;

CREATE TABLE IF NOT EXISTS team_members (
  id INT UNSIGNED AUTO_INCREMENT PRIMARY KEY,
  name VARCHAR(120) NOT NULL, role VARCHAR(120), bio TEXT,
  certifications JSON,                           -- ["DJI","XAG","Eavision"]
  photo_id INT UNSIGNED NULL,
  position INT NOT NULL DEFAULT 0, is_published TINYINT(1) NOT NULL DEFAULT 1,
  FOREIGN KEY (photo_id) REFERENCES media(id) ON DELETE SET NULL
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4;

CREATE TABLE IF NOT EXISTS testimonials (
  id INT UNSIGNED AUTO_INCREMENT PRIMARY KEY,
  author VARCHAR(120) NOT NULL, role VARCHAR(120), content TEXT NOT NULL,
  rating TINYINT UNSIGNED, is_published TINYINT(1) NOT NULL DEFAULT 1, position INT NOT NULL DEFAULT 0
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4;

CREATE TABLE IF NOT EXISTS faqs (
  id INT UNSIGNED AUTO_INCREMENT PRIMARY KEY,
  question VARCHAR(255) NOT NULL, answer TEXT NOT NULL,
  page VARCHAR(40) NOT NULL DEFAULT 'geral',
  position INT NOT NULL DEFAULT 0, is_published TINYINT(1) NOT NULL DEFAULT 1
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4;

CREATE TABLE IF NOT EXISTS seo_pages (
  route VARCHAR(160) PRIMARY KEY,
  title VARCHAR(70), description VARCHAR(170), og_image_id INT UNSIGNED NULL,
  FOREIGN KEY (og_image_id) REFERENCES media(id) ON DELETE SET NULL
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4;

CREATE TABLE IF NOT EXISTS leads (
  id INT UNSIGNED AUTO_INCREMENT PRIMARY KEY,
  name VARCHAR(120) NOT NULL, phone VARCHAR(30), email VARCHAR(150),
  interest VARCHAR(60), message TEXT,
  status ENUM('novo','em_atendimento','concluido') NOT NULL DEFAULT 'novo',
  created_at DATETIME DEFAULT CURRENT_TIMESTAMP
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4;

CREATE TABLE IF NOT EXISTS posts (
  id INT UNSIGNED AUTO_INCREMENT PRIMARY KEY,
  slug VARCHAR(160) NOT NULL UNIQUE,
  title VARCHAR(190) NOT NULL, excerpt VARCHAR(300), body MEDIUMTEXT,
  cover_id INT UNSIGNED NULL, category VARCHAR(60),
  published_at DATETIME NULL, is_published TINYINT(1) NOT NULL DEFAULT 0,
  seo_title VARCHAR(70), seo_description VARCHAR(170),
  FOREIGN KEY (cover_id) REFERENCES media(id) ON DELETE SET NULL
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4;

CREATE TABLE IF NOT EXISTS promotions (
  id INT UNSIGNED AUTO_INCREMENT PRIMARY KEY,
  title VARCHAR(190) NOT NULL, description TEXT,
  image_id INT UNSIGNED NULL, product_id INT UNSIGNED NULL,
  starts_at DATE NULL, ends_at DATE NULL,
  cta_label VARCHAR(80) DEFAULT 'Solicitar orçamento',
  is_published TINYINT(1) NOT NULL DEFAULT 1,
  FOREIGN KEY (image_id) REFERENCES media(id) ON DELETE SET NULL,
  FOREIGN KEY (product_id) REFERENCES products(id) ON DELETE SET NULL
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4;
